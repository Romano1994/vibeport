-- Vibeport schema (MyBatis 매퍼 기준으로 복원)
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS TB_USER (
    USER_NO    VARCHAR(64)  NOT NULL PRIMARY KEY,
    EMAIL      VARCHAR(255) NOT NULL UNIQUE,
    USER_NAME  VARCHAR(100),
    PASSWORD   VARCHAR(255),
    ADMIN_YN   CHAR(1)      DEFAULT 'N',
    ROLE       VARCHAR(20)  DEFAULT 'USER',
    LOCK_YN    CHAR(1)      DEFAULT 'N',
    LOCK_DATE  DATETIME     NULL,
    REG_DATE   DATETIME     DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TB_EMAIL (
    EMAIL     VARCHAR(255) NOT NULL PRIMARY KEY,
    USE_YN    CHAR(1)      DEFAULT 'Y',
    REG_TIME  DATETIME     DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TB_EMAIL_LOG (
    LOG_NO    BIGINT AUTO_INCREMENT PRIMARY KEY,
    SUBJECT   VARCHAR(500),
    EMAIL     VARCHAR(255),
    REG_TIME  DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TB_VERIF_CODE (
    VERIF_NO  BIGINT AUTO_INCREMENT PRIMARY KEY,
    CODE      VARCHAR(20)  NOT NULL,
    EMAIL     VARCHAR(255) NOT NULL,
    CNT       INT          DEFAULT 1,
    REG_TIME  DATETIME     DEFAULT CURRENT_TIMESTAMP,
    KEY IDX_VERIF_EMAIL (EMAIL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TB_CONCERT_INFO (
    CONCERT_NO        INT AUTO_INCREMENT PRIMARY KEY,
    ARTIST_NM_KOR     VARCHAR(200) NOT NULL,
    ARTIST_NM_FOR     VARCHAR(200),
    CONCERT_YEAR      INT NOT NULL,
    CONCERT_MONTH     INT NOT NULL,
    CONCERT_DATE      INT NOT NULL,
    CONCERT_TIME      VARCHAR(50),
    VENUE             VARCHAR(300),
    TCT_SITE          VARCHAR(500),
    TCT_OPEN_AT       VARCHAR(100),
    GENRE             VARCHAR(100),
    POP_SCORE         INT DEFAULT 0,
    ARTIST_IMAGE_URL  VARCHAR(1000),
    SEND_YN           CHAR(1) DEFAULT 'N',
    REG_TIME          DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_CONCERT (ARTIST_NM_KOR, CONCERT_YEAR, CONCERT_MONTH, CONCERT_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TB_ARTIST_MSG (
    MSG_NO            INT AUTO_INCREMENT PRIMARY KEY,
    ARTIST_NM_KOR     VARCHAR(200) NOT NULL,
    CONCERT_YEAR      INT,
    CONCERT_MONTH     INT,
    CONCERT_DATE      INT,
    SUBJECT           VARCHAR(500),
    CONTENT           MEDIUMTEXT,
    ARTIST_IMAGE_URL  VARCHAR(1000),
    SEND_YN           CHAR(1) DEFAULT 'N',
    REG_TIME          DATETIME DEFAULT CURRENT_TIMESTAMP,
    KEY IDX_MSG_CONCERT (ARTIST_NM_KOR, CONCERT_YEAR, CONCERT_MONTH, CONCERT_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
